import json
import numpy as np
from scipy import stats

def run_audit5():
    with open('scratch/final_500seed_qualification_results.json') as f:
        qdata = json.load(f)

    detailed = qdata['detailed']
    seeds = qdata['seeds']

    deltas = np.array([
        detailed['Frozen_Candidate'][str(s)]['reward'] - detailed['Raw_Q50'][str(s)]['reward']
        for s in seeds
    ])
    n = len(deltas)

    # Basic stats
    mean_val = float(np.mean(deltas))
    med_val = float(np.median(deltas))
    trimmed_5 = float(stats.trim_mean(deltas, 0.05))
    trimmed_10 = float(stats.trim_mean(deltas, 0.10))
    winsorized_val = float(np.mean(stats.mstats.winsorize(deltas, limits=[0.05, 0.05])))
    se_val = float(np.std(deltas, ddof=1) / np.sqrt(n))

    # Bootstrap CI
    rng = np.random.default_rng(42)
    boot_means = [np.mean(rng.choice(deltas, size=n, replace=True)) for _ in range(10000)]
    ci_low = float(np.percentile(boot_means, 2.5))
    ci_high = float(np.percentile(boot_means, 97.5))

    # Concentration analysis
    sorted_d = np.sort(deltas) # ascending: negative to positive
    total_agg_gain = float(np.sum(deltas))
    
    # Positive only
    pos_deltas = deltas[deltas > 0]
    total_pos_gain = float(np.sum(pos_deltas))

    # top 1%, 5%, 10%
    n_1pct = int(np.ceil(n * 0.01))
    n_5pct = int(np.ceil(n * 0.05))
    n_10pct = int(np.ceil(n * 0.10))

    top_1pct_gain = float(np.sum(sorted_d[-n_1pct:]))
    top_5pct_gain = float(np.sum(sorted_d[-n_5pct:]))
    top_10pct_gain = float(np.sum(sorted_d[-n_10pct:]))
    bottom_10pct_gain = float(np.sum(sorted_d[:n_10pct]))

    # Percentage of total positive aggregate delta generated by top 10%
    pct_of_total_pos_from_top10 = (top_10pct_gain / total_pos_gain) * 100
    pct_of_net_gain_from_top10 = (top_10pct_gain / total_agg_gain) * 100

    print("=" * 80)
    print("AUDIT 5: EFFECT HETEROGENEITY & GAIN CONCENTRATION")
    print("=" * 80)
    print(f"Mean Delta:            ${mean_val:+,.2f}")
    print(f"Median Delta:          ${med_val:+,.2f}")
    print(f"Trimmed Mean (5%):     ${trimmed_5:+,.2f}")
    print(f"Trimmed Mean (10%):    ${trimmed_10:+,.2f}")
    print(f"Winsorized Mean (5%):  ${winsorized_val:+,.2f}")
    print(f"Standard Error:        ${se_val:,.2f}")
    print(f"95% Bootstrap CI:      [${ci_low:+,.2f}, ${ci_high:+,.2f}]")
    print("-" * 80)
    print(f"Total Net Aggregate Gain:          ${total_agg_gain:+,.2f}")
    print(f"Total Gross Positive Delta:        ${total_pos_gain:+,.2f}")
    print(f"Contribution from Top 1% (N={n_1pct}):      ${top_1pct_gain:+,.2f} ({top_1pct_gain/total_agg_gain*100:.1f}% of net)")
    print(f"Contribution from Top 5% (N={n_5pct}):     ${top_5pct_gain:+,.2f} ({top_5pct_gain/total_agg_gain*100:.1f}% of net)")
    print(f"Contribution from Top 10% (N={n_10pct}):    ${top_10pct_gain:+,.2f} ({top_10pct_gain/total_agg_gain*100:.1f}% of net)")
    print(f"Contribution from Bottom 10% (N={n_10pct}): ${bottom_10pct_gain:+,.2f} ({bottom_10pct_gain/total_agg_gain*100:.1f}% of net)")
    print("-" * 80)
    print(f"Percentage of Total POSITIVE Delta from Top 10%: {pct_of_total_pos_from_top10:.1f}%")

    out = {
        'mean': mean_val,
        'median': med_val,
        'trimmed_mean_5pct': trimmed_5,
        'trimmed_mean_10pct': trimmed_10,
        'winsorized_mean_5pct': winsorized_val,
        'standard_error': se_val,
        'ci95': [ci_low, ci_high],
        'total_aggregate_gain': total_agg_gain,
        'total_positive_gain': total_pos_gain,
        'top_1pct_contribution': top_1pct_gain,
        'top_5pct_contribution': top_5pct_gain,
        'top_10pct_contribution': top_10pct_gain,
        'bottom_10pct_contribution': bottom_10pct_gain,
        'pct_of_pos_delta_from_top10': pct_of_total_pos_from_top10,
        'pct_of_net_delta_from_top10': pct_of_net_gain_from_top10
    }
    with open('scratch/audit5_results.json', 'w') as f:
        json.dump(out, f, indent=2)

if __name__ == '__main__':
    run_audit5()
