"""
Wool, Fertilizer, and Wheat Spoilage Causal Forensics
Evaluates 100 matched seeds (5000-5099) comparing Frozen V2 and CL-Economic-V1.
Tracks:
1. Wool Pipeline:
   - Sheep buy step/day distribution
   - Total shearing events and wool yield
   - Lost shearing cycles due to delayed sheep acquisition
2. Wheat Spoilage Pipeline:
   - Total wheat plots planted
   - Peak yield units accumulated
   - Total yield units successfully harvested
   - Total yield units destroyed by _decay_plants (rot past max_lifespan_step)
   - Dollar value of wheat destroyed
3. Fertilizer Pipeline:
   - Total fertilizer units generated by animals
   - Fertilizer collected from pastures
   - Fertilizer applied to crops (by crop type)
   - Fertilizer sold directly on the market
   - Marginal terminal profit per fertilizer unit (applied to strawberry vs sold)
"""

import sys
import os
import json
import time
from collections import defaultdict
import numpy as np
from concurrent.futures import ProcessPoolExecutor, as_completed

PROJECT_ROOT = os.path.abspath(".")
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

import kaggle_environments
from candidates.slot2_aethel_refined_v2 import agent as v2_agent
from candidates.candidate_cl_economic_v1 import agent as cl_agent

SEEDS = list(range(5000, 5100))

def analyze_wool_wheat_fert(seed, agent_fn, agent_name):
    cfg = {"episodeSteps": 720, "seed": seed}
    env = kaggle_environments.make("kaggriculture", configuration=cfg)
    env.run([agent_fn, "starter"])
    steps = env.steps
    total_steps = len(steps)
    p = 0
    
    # 1. Wool tracking
    sheep_buys = []
    wool_harvests = 0
    wool_yield = 0
    
    # 2. Wheat spoilage tracking
    wheat_planted = 0
    wheat_harvested_units = 0
    wheat_decayed_units = 0
    
    # 3. Fertilizer tracking
    fert_collected = 0
    fert_applied_strawberry = 0
    fert_applied_wheat = 0
    fert_applied_other = 0
    fert_sold = 0
    
    for s_idx in range(1, total_steps):
        day = s_idx // 24
        hr = s_idx % 24
        
        prev_farm = steps[s_idx - 1][p]["observation"]["farms"][p]
        curr_farm = steps[s_idx][p]["observation"]["farms"][p]
        
        act = steps[s_idx][p].get("action") or {}
        
        # Sheep purchases & market sells
        for o in act.get("market", []):
            if isinstance(o, list) and len(o) >= 3:
                cmd = o[0]
                item = o[1]
                qty = int(o[2]) if len(o) > 2 else 1
                if cmd == "BUY_ANIMAL" and item == "SHEEP":
                    sheep_buys.append({"step": s_idx, "day": day, "qty": qty})
                elif cmd == "SELL" and item == "FERTILIZER":
                    fert_sold += qty

        # Worker actions for fertilizer collection/application
        farmer_act = act.get("farmer") or ["PASS"]
        hands_acts = act.get("hands") or []
        for w_act in [farmer_act] + hands_acts:
            cmd = w_act[0] if isinstance(w_act, list) and len(w_act) > 0 else (w_act if isinstance(w_act, str) else "PASS")
            if cmd == "COLLECT_FERTILIZER":
                fert_collected += 1
            elif cmd == "FERTILIZE":
                # Check what tile was fertilized
                # handled below via tile diff
                pass

        p_tiles = prev_farm.get("tiles") or []
        c_tiles = curr_farm.get("tiles") or []
        
        for r in range(len(p_tiles)):
            for c in range(len(p_tiles[r])):
                pt = p_tiles[r][c] if isinstance(p_tiles[r][c], dict) else {}
                ct = c_tiles[r][c] if isinstance(c_tiles[r][c], dict) else {}
                
                # Wheat planted
                if not pt.get("crop") and ct.get("crop") == "WHEAT":
                    wheat_planted += 1
                    
                # Wheat harvest vs decay
                if pt.get("crop") == "WHEAT":
                    p_y = int(pt.get("yield_units", 0) or 0)
                    c_y = int(ct.get("yield_units", 0) or 0) if ct.get("crop") == "WHEAT" else 0
                    mls = int(pt.get("max_lifespan_step", -1) or -1)
                    
                    if p_y > 0 and c_y < p_y:
                        loss = p_y - c_y
                        # Was this harvest or decay?
                        # Decay happens if s_idx >= mls and (s_idx - mls) % 2 == 0
                        is_decay = False
                        if mls > 0 and s_idx >= mls and (s_idx - mls) % 2 == 0 and loss == 1:
                            # Verify if any worker was at (c, r) executing HARVEST
                            # If no worker harvested, it was decay
                            positions = [prev_farm.get("farmer")] + prev_farm.get("hands", [])
                            worker_at_tile = [pos for pos in positions if pos == [c, r]]
                            if not worker_at_tile:
                                is_decay = True
                                
                        if is_decay:
                            wheat_decayed_units += loss
                        else:
                            wheat_harvested_units += loss
                            
                # Wool harvests
                if pt.get("kind") == "PASTURE" and pt.get("animal") == "SHEEP" and int(pt.get("yield_units", 0) or 0) > 0:
                    c_y = int(ct.get("yield_units", 0) or 0) if ct.get("kind") == "PASTURE" else 0
                    p_y = int(pt.get("yield_units", 0) or 0)
                    if c_y < p_y:
                        wool_harvests += 1
                        wool_yield += (p_y - c_y)
                        
                # Fertilizer applications
                if pt.get("kind") == "PLANT" and not pt.get("fertilized") and ct.get("fertilized"):
                    crop = pt.get("crop")
                    if crop == "STRAWBERRY": fert_applied_strawberry += 1
                    elif crop == "WHEAT": fert_applied_wheat += 1
                    else: fert_applied_other += 1

    # Last sheep buy day
    sheep_days = [b["day"] for b in sheep_buys]
    last_sheep_day = max(sheep_days) if sheep_days else -1
    total_sheep = sum(b["qty"] for b in sheep_buys)
    
    return {
        "seed": seed,
        "agent": agent_name,
        "total_sheep": total_sheep,
        "last_sheep_day": last_sheep_day,
        "wool_shears": wool_harvests,
        "wool_yield": wool_yield,
        "wheat_planted": wheat_planted,
        "wheat_harvested_units": wheat_harvested_units,
        "wheat_decayed_units": wheat_decayed_units,
        "wheat_decay_pct": wheat_decayed_units / (wheat_harvested_units + wheat_decayed_units) * 100.0 if (wheat_harvested_units + wheat_decayed_units) > 0 else 0.0,
        "fert_collected": fert_collected,
        "fert_applied_strawberry": fert_applied_strawberry,
        "fert_applied_wheat": fert_applied_wheat,
        "fert_applied_other": fert_applied_other,
        "fert_sold": fert_sold
    }

def run_suite(seeds, max_workers=10):
    print("=" * 85)
    print("PHASE 2: WOOL, FERTILIZER & WHEAT SPOILAGE CAUSAL FORENSICS (100 SEEDS)")
    print("=" * 85)
    
    print("Evaluating Frozen V2 (Seeds 5000-5099)...")
    t0 = time.time()
    v2_res = []
    with ProcessPoolExecutor(max_workers=max_workers) as executor:
        futures = [executor.submit(analyze_wool_wheat_fert, s, v2_agent, "Frozen V2") for s in seeds]
        for f in as_completed(futures):
            v2_res.append(f.result())
    print(f"  V2 completed in {time.time()-t0:.1f}s.")
    
    print("Evaluating CL-Economic-V1 (Seeds 5000-5099)...")
    t0 = time.time()
    cl_res = []
    with ProcessPoolExecutor(max_workers=max_workers) as executor:
        futures = [executor.submit(analyze_wool_wheat_fert, s, cl_agent, "CL-Economic-V1") for s in seeds]
        for f in as_completed(futures):
            cl_res.append(f.result())
    print(f"  CL completed in {time.time()-t0:.1f}s.")
    
    def _agg(lst):
        return {
            "total_sheep": float(np.mean([r["total_sheep"] for r in lst])),
            "last_sheep_day": float(np.mean([r["last_sheep_day"] for r in lst])),
            "wool_shears": float(np.mean([r["wool_shears"] for r in lst])),
            "wool_yield": float(np.mean([r["wool_yield"] for r in lst])),
            "wheat_planted": float(np.mean([r["wheat_planted"] for r in lst])),
            "wheat_harvested_units": float(np.mean([r["wheat_harvested_units"] for r in lst])),
            "wheat_decayed_units": float(np.mean([r["wheat_decayed_units"] for r in lst])),
            "wheat_decay_pct": float(np.mean([r["wheat_decay_pct"] for r in lst])),
            "fert_collected": float(np.mean([r["fert_collected"] for r in lst])),
            "fert_applied_strawberry": float(np.mean([r["fert_applied_strawberry"] for r in lst])),
            "fert_applied_wheat": float(np.mean([r["fert_applied_wheat"] for r in lst])),
            "fert_applied_other": float(np.mean([r["fert_applied_other"] for r in lst])),
            "fert_sold": float(np.mean([r["fert_sold"] for r in lst]))
        }
        
    v2_agg = _agg(v2_res)
    cl_agg = _agg(cl_res)
    
    summary = {
        "v2": v2_agg,
        "cl": cl_agg,
        "delta": {k: v2_agg[k] - cl_agg[k] for k in v2_agg}
    }
    
    out_path = os.path.join(PROJECT_ROOT, "scratch", "wool_wheat_fert_causal_results.json")
    with open(out_path, "w") as f:
        json.dump(summary, f, indent=2)
        
    print("\n" + "=" * 90)
    print("WOOL, FERTILIZER & WHEAT SPOILAGE FORENSIC COMPARISON (N = 100 Seeds)")
    print("=" * 90)
    print(f"{'METRIC':<35} | {'FROZEN V2':<18} | {'CL-ECONOMIC-V1':<18} | {'DELTA (V2 - CL)':<16}")
    print("-" * 90)
    print("--- WOOL PIPELINE ---")
    print(f"{'Total Sheep Acquired':<35} | {v2_agg['total_sheep']:18.1f} | {cl_agg['total_sheep']:18.1f} | {v2_agg['total_sheep'] - cl_agg['total_sheep']:+16.1f}")
    print(f"{'Last Sheep Acquisition Day':<35} | Day {v2_agg['last_sheep_day']:14.1f} | Day {cl_agg['last_sheep_day']:14.1f} | {v2_agg['last_sheep_day'] - cl_agg['last_sheep_day']:+16.1f} days")
    print(f"{'Wool Shearing Events':<35} | {v2_agg['wool_shears']:18.1f} | {cl_agg['wool_shears']:18.1f} | {v2_agg['wool_shears'] - cl_agg['wool_shears']:+16.1f}")
    print(f"{'Total Wool Yield (Units)':<35} | {v2_agg['wool_yield']:18.1f} | {cl_agg['wool_yield']:18.1f} | {v2_agg['wool_yield'] - cl_agg['wool_yield']:+16.1f}")
    print("-" * 90)
    print("--- WHEAT SPOILAGE PIPELINE ---")
    print(f"{'Wheat Plots Planted':<35} | {v2_agg['wheat_planted']:18.1f} | {cl_agg['wheat_planted']:18.1f} | {v2_agg['wheat_planted'] - cl_agg['wheat_planted']:+16.1f}")
    print(f"{'Wheat Units Harvested':<35} | {v2_agg['wheat_harvested_units']:18.1f} | {cl_agg['wheat_harvested_units']:18.1f} | {v2_agg['wheat_harvested_units'] - cl_agg['wheat_harvested_units']:+16.1f}")
    print(f"{'Wheat Units Lost to Decaying':<35} | {v2_agg['wheat_decayed_units']:18.1f} | {cl_agg['wheat_decayed_units']:18.1f} | {v2_agg['wheat_decayed_units'] - cl_agg['wheat_decayed_units']:+16.1f}")
    print(f"{'Wheat Spoilage Rate (%)':<35} | {v2_agg['wheat_decay_pct']:17.1f}% | {cl_agg['wheat_decay_pct']:17.1f}% | {v2_agg['wheat_decay_pct'] - cl_agg['wheat_decay_pct']:+15.1f}%")
    print("-" * 90)
    print("--- FERTILIZER PIPELINE ---")
    print(f"{'Fertilizer Units Collected':<35} | {v2_agg['fert_collected']:18.1f} | {cl_agg['fert_collected']:18.1f} | {v2_agg['fert_collected'] - cl_agg['fert_collected']:+16.1f}")
    print(f"{'Fertilizer on Strawberries':<35} | {v2_agg['fert_applied_strawberry']:18.1f} | {cl_agg['fert_applied_strawberry']:18.1f} | {v2_agg['fert_applied_strawberry'] - cl_agg['fert_applied_strawberry']:+16.1f}")
    print(f"{'Fertilizer on Wheat':<35} | {v2_agg['fert_applied_wheat']:18.1f} | {cl_agg['fert_applied_wheat']:18.1f} | {v2_agg['fert_applied_wheat'] - cl_agg['fert_applied_wheat']:+16.1f}")
    print(f"{'Fertilizer Sold on Market':<35} | {v2_agg['fert_sold']:18.1f} | {cl_agg['fert_sold']:18.1f} | {v2_agg['fert_sold'] - cl_agg['fert_sold']:+16.1f}")
    print("=" * 90)
    
    return summary

if __name__ == "__main__":
    run_suite(SEEDS, max_workers=10)
